#!/usr/bin/env python3
"""Render the public landing page for every registered collection identifier."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath
from typing import Iterable, Mapping

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
IDENTIFIER_ROOT = "https://w3id.org/holobiomicslab/asb-skill/collection"
REPOSITORY_OWNER_PREFIX = "HolobiomicsLab/"
# Last line of every page; write and delete only touch files that carry it.
GENERATED_MARK = "This file is generated by"


def source_path(plugin: Mapping) -> str | None:
    """Return a marketplace entry's normalized collection source path."""
    source = plugin.get("source")
    value = source.get("path") if isinstance(source, Mapping) else source
    if not isinstance(value, str) or not value.strip():
        return None
    return PurePosixPath(value.strip()).as_posix()


def marketplace_name(release: Mapping, marketplace: Mapping) -> str | None:
    """Return the plugin name only when its source is this exact release path."""
    release_path = PurePosixPath(str(release["path"])).as_posix()
    for plugin in marketplace.get("plugins", []):
        if isinstance(plugin, Mapping) and source_path(plugin) == release_path:
            name = plugin.get("name")
            return name if isinstance(name, str) and name else None
    return None


def domain_title(slug: str) -> str:
    """Turn a registry slug into its short display title."""
    words = ["AI" if word == "ai" else word.capitalize() for word in slug.split("-")]
    return " ".join(words)


def release_label(slug: str, tag: object) -> str | None:
    """Remove the domain prefix from a release tag when one exists."""
    if not isinstance(tag, str) or not tag:
        return None
    prefix = f"{slug}-"
    return tag[len(prefix):] if tag.startswith(prefix) else tag


def doi_link(doi: str) -> str:
    """Render one DOI as a canonical HTTPS link."""
    return f"[{doi}](https://doi.org/{doi})"


def current_release(domain: Mapping) -> Mapping:
    """Return the highest-major release row for a domain."""
    return max(domain["releases"], key=lambda item: int(item["version"]))


def state_table(slug: str, domain: Mapping, release: Mapping) -> str:
    """Render manifest publication metadata without placeholder values."""
    label = release_label(slug, release.get("tag"))
    version_doi = release.get("version_doi")
    rows = [
        ("Release label", f"`{label}`" if label else "No release tag was minted for this version."),
        (
            "Version DOI",
            doi_link(version_doi) if version_doi else "None: this version has no public archive.",
        ),
        ("Concept DOI (all archived versions)", doi_link(str(domain["concept_doi"]))),
        ("Release date", str(release["released"])),
        ("Skills", f"{release['skills']:,}"),
        ("Tools", f"{release['tools']:,}"),
        ("Workflows", f"{release['workflows']:,}"),
        ("Papers", f"{release['papers']:,}"),
        ("Content licence", "[CC-BY-4.0](../../../LICENSING.md)"),
    ]
    body = ["| State | Value |", "|---|---|"]
    body.extend(f"| {name} | {value} |" for name, value in rows)
    return "\n".join(body)


def install_commands(plugin_name: str | None) -> list[str]:
    """Return the documented marketplace commands for one advertised row."""
    if not plugin_name:
        return []
    return [
        "Claude Code:\n\n```text",
        "/plugin marketplace add HolobiomicsLab/asb-skill-collections",
        f"/plugin install {plugin_name}@asb-skill-collections\n```",
        "\nCodex CLI:\n\n```text",
        "codex plugin marketplace add HolobiomicsLab/asb-skill-collections",
        f"codex plugin add {plugin_name}@asb-skill-collections\n```\n",
        "The marketplace entry installs from the public domain repository, so these commands "
        "need no read access.\n",
    ]


def availability_section(domain: Mapping, release: Mapping, plugin_name: str | None) -> str:
    """Render only the documented distribution routes available to this row."""
    lines = ["## How to get this collection", "", *install_commands(plugin_name)]
    version_doi = release.get("version_doi")
    current_version = int(current_release(domain)["version"])
    if version_doi:
        lines.append(f"The complete public archive is the Zenodo record {doi_link(version_doi)}.")
    elif int(release["version"]) != current_version:
        lines.append(
            "This version has no public archive. Use the current major, "
            f"[v{current_version}](../v{current_version}/README.md)."
        )
    else:
        lines.append("This version has no public archive yet.")
    return "\n".join(lines)


def content_location(domain: Mapping, release: Mapping) -> str:
    """Name the public source repository and its Zenodo archive without linking either."""
    repository = str(domain["repository"]).removeprefix(REPOSITORY_OWNER_PREFIX)
    archive = (
        "Its archive is the Zenodo record named above."
        if release.get("version_doi")
        else "It has no Zenodo archive."
    )
    return (
        "## Where the content lives\n\n"
        f"The content of this version is kept in the public repository `{repository}`. "
        f"{archive} This registry holds the tooling and the release records, not the content."
    )


def superseded_section(release: Mapping) -> str:
    """Render the earlier patch releases retained in the manifest row."""
    superseded = release.get("superseded") or []
    if not superseded:
        return ""
    lines = [
        "## Earlier releases of this major",
        "",
        "| Tag | Version DOI | Release date |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{item['tag']}` | {doi_link(item['version_doi'])} | {item['released']} |"
        for item in superseded
    )
    return "\n".join(lines)


def opening_text(slug: str, domain: Mapping, release: Mapping) -> str:
    """Explain legacy state, skills, and identifier resolution."""
    version = int(release["version"])
    current_version = int(current_release(domain)["version"])
    lines = []
    if release.get("status") == "legacy":
        lines.append(
            f"**Legacy release.** The registry marks this row as legacy. "
            f"The current major is [v{current_version}](../v{current_version}/README.md)."
        )
    elif version != current_version:
        lines.append(
            f"**Earlier major.** The current major is "
            f"[v{current_version}](../v{current_version}/README.md)."
        )
    lines.append("A skill is a short procedure that an AI agent can read and follow.")
    lines.append(
        f"The identifier `{IDENTIFIER_ROOT}/{slug}/v{version}` resolves to this "
        "public landing page."
    )
    return "\n\n".join(lines)


def registry_section() -> str:
    """Render stable relative links to registry and contribution records."""
    return (
        "## Registry and contribution\n\n"
        "Registry records: [collections.yaml](../../../collections.yaml), "
        "[catalogue.jsonld](../../../catalogue.jsonld), and "
        "[registry documentation](../../../docs/REGISTRY.md).\n\n"
        "To report a problem or contribute, follow the "
        "[contribution loop](../../../docs/CONTRIBUTION_LOOP.md)."
    )


def render_collection_landing(
    slug: str, domain: Mapping, release: Mapping, marketplace: Mapping
) -> str:
    """Build one deterministic landing page from registry-owned inputs."""
    version = int(release["version"])
    sections = [
        f"# {domain_title(slug)} skill collection v{version}",
        opening_text(slug, domain, release),
        state_table(slug, domain, release),
        availability_section(domain, release, marketplace_name(release, marketplace)),
        content_location(domain, release),
        superseded_section(release),
        registry_section(),
        (
            f"{GENERATED_MARK} "
            "[`scripts/render_collection_landings.py`]"
            "(../../../scripts/render_collection_landings.py)."
        ),
    ]
    return "\n\n".join(section for section in sections if section) + "\n"


def expected_landings(manifest: Mapping, marketplace: Mapping) -> dict[Path, str]:
    """Return every manifest-owned landing path and its exact contents."""
    pages = {}
    for slug, domain in manifest["domains"].items():
        for release in domain.get("releases", []):
            relative = Path(str(release["path"])) / "README.md"
            pages[relative] = render_collection_landing(slug, domain, release, marketplace)
    return dict(sorted(pages.items(), key=lambda item: item[0].as_posix()))


def existing_landings(root: Path) -> set[Path]:
    """Find landing-shaped README files currently in the public registry."""
    return {
        path.relative_to(root)
        for path in root.glob("collections/*/v*/README.md")
        if path.is_file()
    }


def differences(root: Path, pages: Mapping[Path, str]) -> list[tuple[str, Path]]:
    """Classify missing, stale, and unexpected generated landing files."""
    problems = []
    for relative, content in pages.items():
        path = root / relative
        if not path.is_file():
            problems.append(("missing", relative))
        elif path.read_text(encoding="utf-8") != content:
            problems.append(("stale", relative))
    expected = set(pages)
    problems.extend(("unexpected", path) for path in existing_landings(root) - expected)
    return sorted(problems, key=lambda item: (item[0], item[1].as_posix()))


def remove_empty_parents(path: Path, stop: Path) -> None:
    """Remove empty generated directories without crossing the collections root."""
    parent = path.parent
    while parent != stop and parent.is_dir():
        try:
            parent.rmdir()
        except OSError:
            return
        parent = parent.parent


def is_generated_landing(path: Path) -> bool:
    """Say whether a README is one of these pages and not a collection's own README."""
    if (path.parent / "collection.yaml").exists():
        return False
    return GENERATED_MARK in path.read_text(encoding="utf-8", errors="replace")


def write_landings(root: Path, pages: Mapping[Path, str]) -> None:
    """Write expected pages and remove landing files no longer in the manifest.

    A content repository keeps a collection's own README at the same relative path. Nothing is
    written or removed when one target is not a generated landing page.
    """
    stale = existing_landings(root) - set(pages)
    foreign = sorted(
        relative.as_posix()
        for relative in (set(pages) | stale)
        if (root / relative).is_file() and not is_generated_landing(root / relative)
    )
    if foreign:
        raise ValueError(
            "refusing to replace or remove files that are not generated landing pages "
            f"(is --root a content repository?): {', '.join(foreign)}"
        )
    for relative, content in pages.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for relative in stale:
        path = root / relative
        path.unlink()
        remove_empty_parents(path, root / "collections")


def load_inputs(manifest_path: Path, marketplace_path: Path) -> tuple[dict, dict]:
    """Load the registry manifest and optional marketplace document."""
    manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
    if not isinstance(manifest, dict) or not isinstance(manifest.get("domains"), dict):
        raise ValueError(f"manifest must contain a domains mapping: {manifest_path}")
    marketplace = (
        json.loads(marketplace_path.read_text(encoding="utf-8"))
        if marketplace_path.is_file()
        else {"plugins": []}
    )
    return manifest, marketplace


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line options."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--marketplace", type=Path)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Render landings or check their committed bytes."""
    args = parse_args(argv)
    root = args.root.resolve()
    manifest_path = args.manifest or root / "collections.yaml"
    marketplace_path = args.marketplace or root / ".claude-plugin/marketplace.json"
    try:
        manifest, marketplace = load_inputs(manifest_path, marketplace_path)
        pages = expected_landings(manifest, marketplace)
    except (OSError, ValueError, json.JSONDecodeError, yaml.YAMLError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    if args.check:
        problems = differences(root, pages)
        for state, relative in problems:
            print(f"{state}: {relative.as_posix()}")
        if problems:
            return 1
        print(f"OK: {len(pages)} collection landing pages are current")
        return 0
    try:
        write_landings(root, pages)
    except ValueError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"wrote {len(pages)} collection landing pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
