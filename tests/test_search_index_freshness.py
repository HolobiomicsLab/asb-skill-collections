"""docs-site/search_index.json is held to the collections it indexes (#53).

The index is generated by docs-site/build_search_index.py and committed. CI
regenerates it into a temporary path and compares the bytes with the committed
file, which only works if two builds of the same tree are byte-identical and
the generator can write somewhere other than the committed path.
"""

from __future__ import annotations

import importlib.util
import json
import pathlib

import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
GENERATOR = REPO / "docs-site" / "build_search_index.py"
VALIDATE = REPO / ".github" / "workflows" / "validate.yml"


def _generator():
    spec = importlib.util.spec_from_file_location("build_search_index", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _tiny_tree(root: pathlib.Path) -> pathlib.Path:
    col = root / "collections" / "demo" / "v1"
    for slug in ("beta", "alpha"):
        d = col / "skills" / slug
        d.mkdir(parents=True)
        (d / "SKILL.md").write_text(
            f"---\nname: {slug}\ndescription: Use when testing {slug}.\n---\n"
            f"## Summary\n\nThe {slug} skill.\n",
            encoding="utf-8",
        )
    (col / "tools").mkdir()
    (col / "tools" / "t.yaml").write_text("slug: t\nname: T\n", encoding="utf-8")
    (col / "corpus.yaml").write_text(
        yaml.safe_dump(
            {
                "collection": "demo",
                "collection_version": 1,
                "papers": [{"doi": "10.1/x", "title": "X", "status": "ok"}],
            }
        ),
        encoding="utf-8",
    )
    return root


def _patched(monkeypatch, tmp_path):
    gen = _generator()
    monkeypatch.setattr(gen, "REPO_ROOT", _tiny_tree(tmp_path / "repo"))
    committed = tmp_path / "committed.json"
    committed.write_text("sentinel", encoding="utf-8")
    monkeypatch.setattr(gen, "OUTPUT", committed)
    return gen, committed


def test_payload_carries_no_build_time(monkeypatch, tmp_path):
    gen, _ = _patched(monkeypatch, tmp_path)
    payload = gen.build_index()
    assert "generated_at" not in payload
    assert [s["name"] for s in payload["skills"]] == ["alpha", "beta"]


def test_two_builds_of_one_tree_are_byte_identical(monkeypatch, tmp_path):
    gen, _ = _patched(monkeypatch, tmp_path)
    assert gen.serialize(gen.build_index()) == gen.serialize(gen.build_index())


def test_output_option_writes_there_and_leaves_the_committed_index(monkeypatch, tmp_path):
    gen, committed = _patched(monkeypatch, tmp_path)
    out = tmp_path / "elsewhere" / "search_index.json"
    assert gen.main(["--output", str(out)]) == 0
    assert out.read_text(encoding="utf-8") == gen.serialize(gen.build_index())
    assert json.loads(out.read_text(encoding="utf-8"))["collections"] == ["demo/v1"]
    assert committed.read_text(encoding="utf-8") == "sentinel"


def test_default_output_is_the_committed_index(monkeypatch, tmp_path):
    gen, committed = _patched(monkeypatch, tmp_path)
    assert gen.main([]) == 0
    assert committed.read_text(encoding="utf-8") == gen.serialize(gen.build_index())


def _freshness_steps():
    workflow = yaml.safe_load(VALIDATE.read_text(encoding="utf-8"))
    return [
        (name, step)
        for name, job in workflow["jobs"].items()
        for step in job.get("steps", [])
        if "build_search_index.py --output" in (step.get("run") or "")
    ]


def test_validate_compares_a_regenerated_index_with_the_committed_one():
    steps = _freshness_steps()
    assert len(steps) == 1, "validate.yml has no step that regenerates the search index"
    job, step = steps[0]
    run = step["run"]
    assert "docs-site/search_index.json" in run
    assert "cmp" in run or "diff" in run
    # The failure names the command that fixes it.
    assert "python docs-site/build_search_index.py" in run
    # A runner-temporary path, never the committed file.
    assert "RUNNER_TEMP" in run
